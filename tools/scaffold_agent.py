#!/usr/bin/env python
"""Scaffold an ``Agent`` subclass with extra state and the copy protocol.

    python tools/scaffold_agent.py --name PSOAgent \
        --state velocity:object pbest_solution:object pbest_fitness:double \
        --out clypto/native/collection/swarm_based/PSO
    python tools/scaffold_agent.py --name TaggedAgent --state tag:object --print

The generated pair implements the two hooks ``cy.duplicate_agent`` dispatches on:

+ ``_new_instance(self)`` — a blank instance of the subclass (``Agent.__new__``
  cannot allocate a subclass safely, so this override is mandatory).
+ ``_copy_state_to(self, other)`` — the base fields first (the ``duplicate_agent``
  guard rejects anything else), then the extras, shared by reference.

Kinds: ``object``, ``double`` (also ``float``), ``int``, ``bint``, ``str`` and
``cnp.ndarray`` (also ``np.ndarray``). ``--print`` shows the files without
writing them; ``--force`` overwrites existing ones.
"""
import argparse
import re
from pathlib import Path

HEADER = "# Generated by tools/scaffold_agent.py — adjust the state list and regenerate.\n"
KINDS = {
    "object": "object",
    "double": "double",
    "float": "double",
    "int": "int",
    "bint": "bint",
    "str": "str",
    "cnp.ndarray": "cnp.ndarray",
    "np.ndarray": "cnp.ndarray",
}
RESERVED = {"solution", "objectives", "weights", "fitness", "_new_instance", "_copy_state_to", "copy", "snapshot"}

PXD_TEMPLATE = HEADER + """
from {base_module} cimport {base}


cdef class {name}({base}):
{fields}
    cdef Agent _new_instance(self)
    cdef void _copy_state_to(self, Agent other)
"""

PYX_TEMPLATE = HEADER + """
{imports}
from {base_module} cimport {base}


cdef class {name}({base}):
    def __cinit__(self):
        # The base __cinit__ does NOT run here (Cython calls the most derived one).
        # Copies overwrite every field anyway; never draw randomness in __cinit__,
        # or duplicate_agent changes the random streams of the run.
        pass

    cdef Agent _new_instance(self):
        return {name}.__new__({name})

    cdef void _copy_state_to(self, Agent other):
        Agent._copy_state_to(self, other)  # the base fields first, always
        cdef {name} target = <{name}>other
{copies}
"""


def snake(name: str) -> str:
    name = re.sub("(.)([A-Z][a-z]+)", r"\1_\2", name)
    return re.sub("([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def parse_state(entries: list[str]) -> dict[str, str]:
    fields: dict[str, str] = {}
    for entry in entries:
        name, _, kind = entry.rpartition(":")
        name, kind = name.strip(), kind.strip()
        if not name or not kind or kind not in KINDS:
            raise SystemExit(f"bad --state entry {entry!r}: 'field:kind' with kind in {sorted(KINDS)}")
        if not re.fullmatch(r"[a-zA-Z_]\w*", name):
            raise SystemExit(f"bad --state entry {entry!r}: invalid identifier")
        if name in RESERVED:
            raise SystemExit(f"field {name!r} is reserved by Agent; extras are any other name")
        if name in fields:
            raise SystemExit(f"field {name!r} listed twice")
        fields[name] = KINDS[kind]
    return fields


def render(name: str, base: str, base_module: str, fields: dict[str, str]) -> tuple[str, str]:
    needs_numpy = any(kind == "cnp.ndarray" for kind in fields.values())
    fields_src = "".join(f"    cdef public {kind} {field}\n" for field, kind in fields.items())
    copies_src = "\n".join(f"        target.{field} = self.{field}" for field in fields)

    pxd = PXD_TEMPLATE.format(
        base_module=base_module, base=base, name=name, fields=fields_src
    ).lstrip("\n")
    pyx = PYX_TEMPLATE.format(
        imports=("import numpy as np\ncimport numpy as cnp\n\n" if needs_numpy else ""),
        base_module=base_module, base=base, name=name, copies=copies_src,
    ).lstrip("\n")
    return pxd, pyx


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--name", required=True, help="the new agent class (e.g. PSOAgent)")
    parser.add_argument("--base", default="Agent", help="the base agent class (default: Agent)")
    parser.add_argument("--base-module", default="clypto.optimizer.native.agent",
                        help="module of the base class (default: the engine's agent)")
    parser.add_argument("--state", default=[], nargs="+",
                        help="extra fields as field:kind pairs (object, double, int, bint, str, cnp.ndarray)")
    parser.add_argument("--out", default="", help="directory for <snake>.pxd/.pyx (default: cwd)")
    parser.add_argument("--print", dest="show", action="store_true", help="print the files, write nothing")
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    args = parser.parse_args()

    if not re.fullmatch(r"[A-Z]\w*", args.name):
        raise SystemExit("--name must be a PascalCase class name")
    if not re.fullmatch(r"\w+", args.base):
        raise SystemExit("--base must be a class name")
    fields = parse_state(args.state)
    pxd, pyx = render(args.name, args.base, args.base_module, fields)

    if args.show:
        print(f"### {snake(args.name)}.pxd\n{pxd}\n### {snake(args.name)}.pyx\n{pyx}", end="")
        return
    out = Path(args.out) if args.out else Path(".")
    out.mkdir(parents=True, exist_ok=True)
    for suffix, text in ((".pxd", pxd), (".pyx", pyx)):
        target = out / f"{snake(args.name)}{suffix}"
        if target.exists() and not args.force:
            raise SystemExit(f"{target} exists; use --force to overwrite")
        target.write_text(text)
        print(f"wrote {target}")


if __name__ == "__main__":
    main()
